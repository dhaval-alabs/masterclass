#!/usr/bin/env bash
# Builds supabase/fresh-setup.sql: every migration in order, inside ONE transaction, so a new
# Supabase project gets the full excel_to_ai schema in a single run — and a failure part-way
# leaves nothing behind (just fix and re-run).
set -euo pipefail
cd "$(dirname "$0")/.."
OUT=supabase/fresh-setup.sql
{
  echo "-- excel_to_ai — full schema for a NEW Supabase project (migrations 0001..latest, in order)."
  echo "-- Generated by scripts/build-fresh-setup.sh — edit the migrations, not this file."
  echo "-- BEFORE RUNNING: replace <LP_PASSWORD> (once, in 0001) with the password for the app login."
  echo "-- Runs as one transaction: if anything fails, nothing is created; fix it and run again."
  echo "begin;"
  for f in $(ls supabase/migrations/*.sql | sort); do
    echo; echo "-- ===== $(basename "$f") ====="; cat "$f"; echo
  done
  echo; echo "commit;"
} > "$OUT"
echo "wrote $OUT ($(wc -c < "$OUT") bytes)"
